using System.Text;
using Sellora.AuditService.Application.Exports;

namespace Sellora.AuditService.Tests.Unit;

public sealed class CsvExportWriterTests
{
    private static readonly ExportStamp Stamp = new(
        "Asha Fernando", new DateTimeOffset(2026, 10, 14, 15, 30, 0, TimeSpan.FromHours(5.5)), "from: 2026-09-01; to: 2026-09-30", "Whole company");

    [Fact]
    public void The_file_starts_with_a_utf8_bom_and_uses_crlf()
    {
        var bytes = CsvExportWriter.Write(Table());

        Assert.Equal(new byte[] { 0xEF, 0xBB, 0xBF }, bytes[..3]);
        var text = Text(bytes);
        Assert.Contains("\r\n", text);
        Assert.DoesNotContain("\n", text.Replace("\r\n", string.Empty));
        Assert.EndsWith("\r\n", text);
    }

    [Fact]
    public void The_header_block_comes_before_the_table()
    {
        var lines = Text(CsvExportWriter.Write(Table())).Split("\r\n");

        Assert.Equal("Sales breakdown by agency", lines[0]);
        Assert.Equal("Generated by,Asha Fernando", lines[1]);
        Assert.Equal("Generated at,2026-10-14 10:00:00 UTC", lines[2]);
        Assert.Equal("Filters,from: 2026-09-01; to: 2026-09-30", lines[3]);
        Assert.Equal("Scope,Whole company", lines[4]);
        Assert.Equal(string.Empty, lines[5]);
        Assert.Equal("Agency,Orders,Sales (LKR)", lines[6]);
        Assert.Equal("Kandy Agency,3,1500.00", lines[7]);
    }

    [Theory]
    [InlineData("plain", "plain")]
    [InlineData("a,b", "\"a,b\"")]
    [InlineData("say \"hi\"", "\"say \"\"hi\"\"\"")]
    [InlineData("two\r\nlines", "\"two\r\nlines\"")]
    [InlineData("line\nbreak", "\"line\nbreak\"")]
    public void Fields_are_quoted_per_rfc_4180(string value, string expected)
    {
        Assert.Equal(expected, CsvExportWriter.Field(value));
    }

    [Theory]
    [InlineData("=HYPERLINK(\"http://x\")", "\"'=HYPERLINK(\"\"http://x\"\")\"")]
    [InlineData("+1+1", "'+1+1")]
    [InlineData("-2+3", "'-2+3")]
    [InlineData("@SUM(A1)", "'@SUM(A1)")]
    [InlineData("\tcmd", "'\tcmd")]
    public void Text_that_looks_like_a_formula_gets_a_leading_apostrophe(string value, string expected)
    {
        Assert.Equal(expected, CsvExportWriter.Field(value));
    }

    [Fact]
    public void Numbers_stay_numbers_even_when_negative()
    {
        Assert.Equal("-3800.00", CsvExportWriter.Field(-3800m));
        Assert.Equal("-84.4", CsvExportWriter.Field(ExportCell.Percent(-84.4m)));
        Assert.Equal("12", CsvExportWriter.Field(12));
    }

    [Fact]
    public void Sinhala_and_tamil_names_survive()
    {
        var table = Table() with { Rows = new[] { new ExportCell[] { "කොළඹ ඒජන්සිය", 1, 10m }, new ExportCell[] { "யாழ்ப்பாணம்", 2, 20m } } };

        var text = Text(CsvExportWriter.Write(table));

        Assert.Contains("කොළඹ ඒජන්සිය,1,10.00", text);
        Assert.Contains("யாழ்ப்பாணம்,2,20.00", text);
    }

    [Fact]
    public void A_requester_name_that_looks_like_a_formula_is_protected_in_the_header()
    {
        var table = Table() with { Stamp = Stamp with { GeneratedBy = "=cmd|' /C calc'!A0" } };

        Assert.Contains("Generated by,'=cmd|' /C calc'!A0", Text(CsvExportWriter.Write(table)));
    }

    private static ExportTable Table() => new(
        "Sales breakdown by agency",
        Stamp,
        new[] { "Agency", "Orders", "Sales (LKR)" },
        new[] { new ExportCell[] { "Kandy Agency", 3, 1500m } });

    private static string Text(byte[] bytes) => new UTF8Encoding(false).GetString(bytes, 3, bytes.Length - 3);
}
