        var colombo = EventBuilder.Party(Guid.NewGuid(), "Colombo Agency", "Nimal, \"Senior\" Rep");
        var galle = EventBuilder.Party(Guid.NewGuid(), "ගාල්ල ඒජන්සිය", "=Sunil");
        var day = new DateTimeOffset(2026, 9, 10, 4, 0, 0, TimeSpan.Zero);

        await using var harness = new AuditHarness(fixture);
        await harness.IngestAllAsync(new[]
        {
            EventBuilder.AgencyRegistered(_company, colombo),
            EventBuilder.AgencyRegistered(_company, galle),
            EventBuilder.SalesRepAssigned(_company, colombo),
            EventBuilder.SalesRepAssigned(_company, galle),
            EventBuilder.Order(_company, "OrderConfirmed", Guid.NewGuid(), "ORD-W-1", colombo, day, 1250.50m, "Confirmed"),
            EventBuilder.Order(_company, "OrderConfirmed", Guid.NewGuid(), "ORD-W-2", colombo, day.AddDays(3), 749.50m, "Confirmed"),
            EventBuilder.Order(_company, "OrderConfirmed", Guid.NewGuid(), "ORD-W-3", galle, day.AddDays(5), 2000m, "Confirmed"),
            EventBuilder.Order(_company, "OrderPlaced", Guid.NewGuid(), "ORD-W-4", galle, day.AddDays(6), 300m, "Placed")
        });
    }

    public async Task DisposeAsync() => await _api.DisposeAsync();

    [Theory]
    [InlineData("rep", "value", "desc")]
    [InlineData("agency", "name", "asc")]
    [InlineData("territory", "count", "desc")]
    [InlineData("product", "value", "asc")]
    public async Task A_breakdown_csv_has_exactly_the_on_screen_rows_and_figures(string groupBy, string sort, string direction)
    {
        using var client = _api.CreateClientAs("CompanyAdmin", _company, "admin-figures");
        var onScreen = await client.GetFromJsonAsync<SalesBreakdownResponse>(
            $"/api/reports/sales-breakdown?groupBy={groupBy}&{September}&sort={sort}&direction={direction}");

        var lines = await ExportCsvAsync(client, new
        {
            reportType = "sales-breakdown",
            format = "csv",
            filters = new { from = "2026-09-01", to = "2026-09-30", groupBy, sort, direction }
        });

        var table = lines.SkipWhile(line => line.Length > 0).Skip(2).Where(line => line.Length > 0).ToList();
        var expected = onScreen!.Rows
            .Select(row => Csv(row.Name, row.OrderCount, row.SalesValue, row.AverageOrderValue))
            .Append(Csv("Total", onScreen.TotalOrderCount, onScreen.TotalSalesValue, ReportMath.Average(onScreen.TotalSalesValue, onScreen.TotalOrderCount)))
            .ToList();

        Assert.Equal(expected, table);
        Assert.Equal("Generated by,admin-figures", lines[1]);
        Assert.Equal("Scope,Company-wide", lines[4]);
    }

    [Fact]
    public async Task A_summary_csv_has_the_on_screen_totals_statuses_and_days()
    {
        using var client = _api.CreateClientAs("CompanyAdmin", _company, "admin-summary");
        var onScreen = await client.GetFromJsonAsync<SalesSummaryResponse>(
            $"/api/reports/sales-summary?{September}&compareFrom=2026-08-01&compareTo=2026-08-31");

        var lines = await ExportCsvAsync(client, new
        {
            reportType = "sales-summary",
            format = "csv",
            filters = new { from = "2026-09-01", to = "2026-09-30", compareFrom = "2026-08-01", compareTo = "2026-08-31" }
        });

        Assert.Equal(4000m, onScreen!.Totals.SalesValue);
        Assert.Contains(Csv("Totals", "Sales 2026-09-01 to 2026-09-30", onScreen.Totals.OrderCount, onScreen.Totals.SalesValue), lines);
        Assert.Contains($"Totals,Outstanding,,{Money(onScreen.Totals.Outstanding)}", lines);
        Assert.All(onScreen.StatusBreakdown, status => Assert.Contains($"Orders by status,{status.Status},{status.Count},", lines));
        Assert.All(onScreen.Daily, day => Assert.Contains(Csv("Daily", day.Date.ToString("yyyy-MM-dd", Invariant), day.OrderCount, day.SalesValue), lines));
        Assert.Contains($"Comparison,Sales 2026-08-01 to 2026-08-31,{onScreen.Comparison!.Totals.OrderCount},{Money(onScreen.Comparison.Totals.SalesValue)}", lines);
    }

    [Fact]
    public async Task A_long_range_is_accepted_at_once_and_completes_through_the_queue()
    {
        using var client = _api.CreateClientAs("CompanyAdmin", _company, "admin-long");

        var response = await client.PostAsJsonAsync("/api/reports/export", new
        {
            reportType = "sales-breakdown",
            format = "pdf",
            filters = new { from = "2024-01-01", to = "2027-01-04", groupBy = "product" }
        });
        var exportId = (await response.Content.ReadFromJsonAsync<ExportAccepted>())!.ExportId;

        Assert.Equal(HttpStatusCode.Accepted, response.StatusCode);
        Assert.Equal("Queued", (await client.GetFromJsonAsync<ExportStatusResponse>($"/api/reports/export/{exportId}"))!.Status);

        await ExportRunner.DrainAsync(ExportRunner.Worker(_api.Services));

        var status = await client.GetFromJsonAsync<ExportStatusResponse>($"/api/reports/export/{exportId}");
        Assert.Equal("Ready", status!.Status);
        Assert.NotNull(status.StartedAt);
        Assert.Equal(status.CompletedAt!.Value.AddHours(24), status.ExpiresAt);
    }

    [Fact]
    public async Task Two_workers_never_claim_the_same_job()
    {
        await using var api = new CountingApi(fixture.AppConnectionString);
        using var client = api.CreateClientAs("CompanyAdmin", _company, "admin-race");
        var ids = new List<Guid>();

        for (var index = 0; index < 24; index++)
        {
            var response = await client.PostAsJsonAsync("/api/reports/export", new
            {
                reportType = "sales-summary",
                format = "csv",
                filters = new { from = "2026-09-01", to = "2026-09-30" }
            });
            ids.Add((await response.Content.ReadFromJsonAsync<ExportAccepted>())!.ExportId);
        }

        var runs = await Task.WhenAll(
            Task.Run(() => ExportRunner.DrainAsync(ExportRunner.Worker(api.Services))),
            Task.Run(() => ExportRunner.DrainAsync(ExportRunner.Worker(api.Services))));

        Assert.All(ids, id => Assert.Equal(1, api.Generated.GetValueOrDefault(id)));
        Assert.True(runs.Sum() >= ids.Count);

        await using var owner = fixture.CreateOwnerContext(new TenantStub(_company));
        var statuses = await owner.ReportExports.AsNoTracking().Where(export => ids.Contains(export.ExportId)).Select(export => export.Status).ToListAsync();
        Assert.All(statuses, status => Assert.Equal(ExportStatus.Ready, status));
    }

    [Fact]
    public async Task A_failing_job_becomes_failed_with_a_short_message_and_the_worker_goes_on()
    {
        await using var api = new CountingApi(fixture.AppConnectionString);
        using var client = api.CreateClientAs("CompanyAdmin", _company, "admin-fail");
        var body = new { reportType = "sales-summary", format = "csv", filters = new { from = "2026-09-01", to = "2026-09-30" } };

        var first = (await (await client.PostAsJsonAsync("/api/reports/export", body)).Content.ReadFromJsonAsync<ExportAccepted>())!.ExportId;
        var second = (await (await client.PostAsJsonAsync("/api/reports/export", body)).Content.ReadFromJsonAsync<ExportAccepted>())!.ExportId;
        api.FailId = first;

        await ExportRunner.DrainAsync(ExportRunner.Worker(api.Services));

        var failed = await client.GetFromJsonAsync<ExportStatusResponse>($"/api/reports/export/{first}");
        Assert.Equal("Failed", failed!.Status);
        Assert.Equal(ExportWorkerService.FailureMessage, failed.Error);
        Assert.DoesNotContain("at ", failed.Error);
        Assert.Equal("Ready", (await client.GetFromJsonAsync<ExportStatusResponse>($"/api/reports/export/{second}"))!.Status);
    }

    [Fact]
    public async Task An_audit_extract_holds_the_searched_entries_with_payloads()
    {
        using var client = _api.CreateClientAs("CompanyAdmin", _company, "admin-audit");
        var onScreen = await client.GetFromJsonAsync<PagedResponse<AuditEntrySummary>>("/api/audit?eventType=OrderConfirmed&pageSize=100");

        var lines = await ExportCsvAsync(client, new { reportType = "audit-extract", format = "csv", filters = new { eventType = "OrderConfirmed" } });

        var rows = lines.SkipWhile(line => line.Length > 0).Skip(2).Where(line => line.Length > 0).ToList();
        Assert.Equal(3, onScreen!.TotalCount);
        Assert.Equal(onScreen.Items.Select(item => item.ChainPosition.ToString(Invariant)), rows.Select(row => row.Split(',')[0]));
        Assert.Contains("Rows,3", lines);
        Assert.Contains("Filters,eventType: OrderConfirmed", lines);
        Assert.All(rows, row => Assert.Contains("ORD-W-", row));
    }

    [Theory]
    [InlineData(null)]
    [InlineData("ORD-W-1")]
    public async Task Audit_extract_pages_match_the_search_order_without_gaps(string? orderReference)
    {
        await using var harness = new AuditHarness(fixture, _company);
        var reads = new AuditReadService(harness.Db);
        var scope = new AuditReadScope(_company, null);
        var query = new AuditSearchQuery(OrderReference: orderReference, PageSize: 100);

        var all = (await reads.SearchAsync(scope, query, CancellationToken.None)).Items.Select(item => item.ChainPosition).ToList();
        var paged = new List<long>();
        AuditExtractCursor? cursor = null;

        while (true)
        {
            var page = await reads.ExtractPageAsync(scope, query, cursor, 3, CancellationToken.None);
            paged.AddRange(page.Select(entry => entry.ChainPosition));

            if (page.Count < 3)
            {
                break;
            }

            cursor = new AuditExtractCursor(page[^1].OccurredAt, page[^1].ChainPosition);
        }

        Assert.NotEmpty(all);
        Assert.Equal(all, paged);
    }

    private async Task<string[]> ExportCsvAsync(HttpClient client, object body)
    {
        var response = await client.PostAsJsonAsync("/api/reports/export", body);
        Assert.Equal(HttpStatusCode.Accepted, response.StatusCode);
        var exportId = (await response.Content.ReadFromJsonAsync<ExportAccepted>())!.ExportId;

        await ExportRunner.DrainAsync(ExportRunner.Worker(_api.Services));

        var file = await client.GetAsync($"/api/reports/export/{exportId}/file");
        Assert.Equal(HttpStatusCode.OK, file.StatusCode);
        return ExportRunner.CsvLines(await file.Content.ReadAsByteArrayAsync());
    }

    private static string Csv(params object[] cells) => string.Join(",", cells.Select(cell => cell switch
    {
        decimal amount => Money(amount),
        int count => count.ToString(Invariant),
        string text => CsvExportWriter.Field(text),
        _ => cell.ToString()
    }));

    private static string Money(decimal value) => value.ToString("0.00", Invariant);

    private sealed class DatabaseApi(string connectionString) : AuditApiFactory(connectionString);

    /// <summary>Counts generations per export, with a pause to widen any race between workers.</summary>
    private sealed class CountingApi(string connectionString) : AuditApiFactory(connectionString)
    {
        public ConcurrentDictionary<Guid, int> Generated { get; } = new();

        public Guid? FailId { get; set; }

        protected override void ConfigureWebHost(IWebHostBuilder builder)
        {
            base.ConfigureWebHost(builder);
            builder.ConfigureTestServices(services => services.AddScoped<IExportGenerator>(_ => new CountingGenerator(this)));
        }

        private sealed class CountingGenerator(CountingApi api) : IExportGenerator
        {
            public async Task<ExportFile> GenerateAsync(ReportExport export, CancellationToken cancellationToken)
            {
                api.Generated.AddOrUpdate(export.ExportId, 1, (_, count) => count + 1);
                await Task.Delay(20, cancellationToken);

                if (export.ExportId == api.FailId)
                {
                    throw new InvalidOperationException("Simulated failure with a long internal detail\n   at Some.Stack.Frame()");
                }

                return new ExportFile("x.csv", CsvExportWriter.ContentType, new byte[] { 1 });
            }
        }
    }
