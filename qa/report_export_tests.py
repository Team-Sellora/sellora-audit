"""
US-E7-3 QA - report export (CSP-253).

Writes evidence/CSP-253/api/report-export-<target>.txt and keeps every downloaded file in evidence/CSP-253/files/:
  US-E7-3-Q1  CSV and PDF match the screen: same rows and figures as GET sales-breakdown with the same filters;
              header shows user, time and filters; CSV is UTF-8 with BOM (Sinhala/Tamil names in Excel)
  US-E7-3-Q2  Scope: an Area Manager's export has no other province anywhere in the file
  US-E7-3-Q3  Large export: a full year returns a job ID at once (no gateway timeout) and is ready later
  US-E7-3-Q4  Access and expiry: another user downloading -> 404; after expiry -> 410 and content null
  US-E7-3-D1  Content-Disposition exposed to the SPA through APIM / CORS; audit extract is Company Admin only

Export API (backlog US-E7-3-BE1):
  POST /api/reports/export              { reportType, format: csv|pdf, filters{...} } -> 202 { exportId }
  GET  /api/reports/export/{id}         status Queued | Running | Ready | Failed | Expired
  GET  /api/reports/export/{id}/file    the file (same user only, before ExpiresAt)

Run:  python report_export_tests.py --target staging
"""
import argparse
import csv
import io
import shutil
import subprocess
import tempfile
import time
from datetime import timedelta

from sellora_qa import (Api, Db, Report, SetupError, audit_base, build_scenario, ci_get, colombo_today,
                        delivery_base, items_of, load_env, poll, run_case, standard_args)

STORY = "CSP-253"
BOM = b"\xef\xbb\xbf"


class Exports:
    def __init__(self, s, base):
        self.s, self.api = s, Api(base, "exports")

    def submit(self, report_type, fmt, filters, persona="admin"):
        return self.api.post("/api/reports/export", {"reportType": report_type, "format": fmt, "filters": filters},
                             self.s.token(persona))

    def status(self, export_id, persona="admin"):
        return self.api.get(f"/api/reports/export/{export_id}", self.s.token(persona))

    def wait_ready(self, export_id, persona="admin", timeout=180):
        def ready():
            state = ci_get(self.status(export_id, persona).body, "status")
            return state if state in ("Ready", "Failed", "Expired") else None
        return poll(ready, timeout=timeout, interval=3)

    def file(self, export_id, persona="admin", origin=None):
        headers = {"Origin": origin} if origin else None
        return self.api.get(f"/api/reports/export/{export_id}/file", self.s.token(persona), headers=headers)


def export_id_of(response):
    return ci_get(response.body, "exportId") or ci_get(response.body, "id")


def deployed(ex, ctx):
    if "deployed" not in ctx:
        probe = ex.api.post("/api/reports/export", {}, ex.s.token("admin"))  # implemented: 400 validation error
        ctx["deployed"] = probe.status not in (0, 404, 405, 502)
        ctx["probe"] = probe
    if not ctx["deployed"]:
        raise SetupError(f"/api/reports/export not deployed ({ctx['probe'].status})")


def header_value(response, name):
    for key, value in response.headers.items():
        if key.lower() == name.lower():
            return value
    return ""


def csv_rows(raw):
    text = raw.decode("utf-8-sig", errors="replace")
    return list(csv.reader(io.StringIO(text)))


def run_export(ex, r, label, report_type, fmt, filters, persona="admin"):
    started = time.perf_counter()
    response = ex.submit(report_type, fmt, filters, persona)
    took = (time.perf_counter() - started) * 1000
    r.expect_status(f"{label} submit returns 202 with an export ID", response, 202)
    export_id = export_id_of(response)
    if not export_id:
        raise SetupError(f"no exportId in {response.text[:200]}")
    state = ex.wait_ready(export_id, persona)
    r.check(f"{label} job reaches Ready", state == "Ready", f"status {state}")
    return export_id, took


def q1_matches_screen(s, r, ctx, ex):
    deployed(ex, ctx)
    start, end = ctx["range"]
    filters = {"from": str(start), "to": str(end), "groupBy": "agency"}
    screen = ex.api.get(f"/api/reports/sales-breakdown?groupBy=agency&from={start}&to={end}", s.token("admin"))
    rows_on_screen = items_of(screen.body)
    export_id, _ = run_export(ex, r, "Q1 CSV", "sales-breakdown", "csv", filters)
    download = ex.file(export_id)
    r.expect_status("Q1 CSV download", download, 200)
    r.attach(f"files/US-E7-3-Q1-breakdown-{export_id}.csv", download.raw)
    r.check("Q1 Content-Type text/csv", "text/csv" in header_value(download, "Content-Type"), header_value(download, "Content-Type"))
    r.check("Q1 UTF-8 with BOM", download.raw.startswith(BOM), str(download.raw[:3]))
    rows = csv_rows(download.raw)
    flat = " ".join(" ".join(row) for row in rows[:8]).lower()
    name = s.env.get("ADMIN_A_DISPLAY_NAME", "")
    r.check("Q1 header: generated by (requester's name)", "generated by" in flat and (not name or name.lower() in flat), flat[:200])
    r.check("Q1 header: generated at", "generated at" in flat)
    r.check("Q1 header: filters (dates and grouping)", str(start) in flat and str(end) in flat and "agency" in flat, flat[:300])
    names_in_file = {row[0] for row in rows if row}
    names_on_screen = {str(ci_get(x, "name") or ci_get(x, "label")) for x in rows_on_screen}
    r.check(f"Q1 every on-screen row ({len(names_on_screen)}) is in the CSV", names_on_screen <= names_in_file,
            f"missing {sorted(names_on_screen - names_in_file)[:5]}")
    for item in rows_on_screen:
        label = str(ci_get(item, "name") or ci_get(item, "label"))
        row = next((x for x in rows if x and x[0] == label), None)
        value = ci_get(item, "salesValue") or ci_get(item, "totalSales") or ci_get(item, "value") or 0
        r.check(f"Q1 '{label}' figure {value} matches", row is not None and any(_same_number(cell, value) for cell in row),
                str(row))

    export_id, _ = run_export(ex, r, "Q1 PDF", "sales-breakdown", "pdf", filters)
    pdf = ex.file(export_id)
    r.attach(f"files/US-E7-3-Q1-breakdown-{export_id}.pdf", pdf.raw)
    r.check("Q1 PDF is a PDF (application/pdf, %PDF)", "application/pdf" in header_value(pdf, "Content-Type")
            and pdf.raw.startswith(b"%PDF"), header_value(pdf, "Content-Type"))
    text = pdf_text(pdf.raw)
    if text is None:
        r.manual("Q1 PDF content", ["Open the PDF in evidence/CSP-253/files/ and compare it row by row with the screen",
                                    "(install poppler-utils for pdftotext to automate this)"])
    else:
        r.check("Q1 PDF lists every on-screen row", all(n in text for n in names_on_screen),
                f"missing {[n for n in names_on_screen if n not in text][:5]}")
        r.check("Q1 PDF header shows generated by / at", "generated by" in text.lower() and "generated at" in text.lower())


def _same_number(cell, value):
    try:
        return round(float(str(cell).replace(",", "").replace("LKR", "").strip()), 2) == round(float(value), 2)
    except ValueError:
        return False


def pdf_text(raw):
    if not shutil.which("pdftotext"):
        return None
    with tempfile.NamedTemporaryFile(suffix=".pdf", delete=False) as handle:
        handle.write(raw)
    result = subprocess.run(["pdftotext", "-layout", handle.name, "-"], capture_output=True, text=True)
    return result.stdout


def q2_area_manager(s, r, ctx, ex):
    deployed(ex, ctx)
    if not s.has("am"):
        raise SetupError("TOKEN_AREA_MANAGER_A not set")
    start, end = ctx["range"]
    admin_rows = items_of(ex.api.get(f"/api/reports/sales-breakdown?groupBy=agency&from={start}&to={end}", s.token("admin")).body)
    am_rows = items_of(ex.api.get(f"/api/reports/sales-breakdown?groupBy=agency&from={start}&to={end}", s.token("am")).body)
    am_names = {str(ci_get(x, "name")) for x in am_rows}
    foreign = {str(ci_get(x, "name")) for x in admin_rows} - am_names
    for fmt in ("csv", "pdf"):
        export_id, _ = run_export(ex, r, f"Q2 AM {fmt.upper()}", "sales-breakdown", fmt,
                                  {"from": str(start), "to": str(end), "groupBy": "agency"}, persona="am")
        download = ex.file(export_id, persona="am")
        r.attach(f"files/US-E7-3-Q2-am-{export_id}.{fmt}", download.raw)
        text = download.raw.decode("utf-8-sig", errors="replace") if fmt == "csv" else pdf_text(download.raw)
        if text is None:
            r.manual(f"Q2 AM {fmt.upper()} content", [f"Open files/US-E7-3-Q2-am-{export_id}.{fmt} - no agency from another "
                                                      "province, header shows the AM's scope",
                                                      "(install poppler-utils for pdftotext to automate this)"])
            continue
        leaked = [n for n in foreign if n and n in text]
        r.check(f"Q2 AM {fmt.upper()} has no agency from another province", not leaked, str(leaked[:5]))
        r.check(f"Q2 AM {fmt.upper()} header shows the AM's scope (provinces)", "scope" in text.lower() or "province" in text.lower())
    for report_type in ("sales-summary", "audit-extract"):
        response = ex.submit(report_type, "csv", {"from": str(start), "to": str(end)}, persona="am")
        expected = (403,) if report_type == "audit-extract" else (202,)
        r.expect_status(f"Q2 AM exports {report_type}", response, *expected)


def q3_large(s, r, ctx, ex):
    deployed(ex, ctx)
    end = colombo_today()
    start = end - timedelta(days=365)
    export_id, took = run_export(ex, r, "Q3 full year CSV", "sales-breakdown", "csv",
                                 {"from": str(start), "to": str(end), "groupBy": "rep"})
    r.check(f"Q3 submit answered at once ({took:.0f} ms, under 2000 ms, no gateway timeout)", took < 2000)
    ctx["large_export"] = export_id


def q4_access_expiry(s, r, ctx, ex):
    deployed(ex, ctx)
    start, end = ctx["range"]
    export_id, _ = run_export(ex, r, "Q4 setup CSV", "sales-breakdown", "csv",
                              {"from": str(start), "to": str(end), "groupBy": "territory"})
    for persona in ("am", "admin_b"):
        if s.has(persona):
            r.expect_status(f"Q4 {persona} downloads someone else's export", ex.file(export_id, persona), 404)
            r.expect_status(f"Q4 {persona} reads someone else's export status", ex.status(export_id, persona), 404)
    db = Db(s.env.get("LOCAL_AUDIT_DB_CONTAINER", ""), s.env.get("LOCAL_AUDIT_DB_NAME", "audit_db"),
            s.env.get("LOCAL_AUDIT_DB_OWNER", "audit_owner"))
    if s.target == "local" and db.configured:
        db.rows(f"UPDATE reporting.report_export SET expires_at = now() - interval '1 minute' WHERE export_id = '{export_id}'")
        r.expect_status("Q4 download after ExpiresAt", ex.file(export_id), 410)
        r.manual("Q4 content nulled by the hourly cleanup", [
            f"After the next hourly run: SELECT status, content IS NULL FROM reporting.report_export WHERE export_id = '{export_id}'",
            "status Expired, content IS NULL = true"])
    else:
        r.manual("Q4 expiry", [f"Export {export_id} created now. Download it again after 24 hours -> 410",
                               "Then in audit_db: status Expired and content IS NULL"])


def d1_headers(s, r, ctx, ex):
    deployed(ex, ctx)
    start, end = ctx["range"]
    export_id, _ = run_export(ex, r, "D1 CSV", "sales-breakdown", "csv", {"from": str(start), "to": str(end), "groupBy": "agency"})
    origin = s.env.get("WEB_ORIGIN", "https://test.selloralk.tech")
    download = ex.file(export_id, origin=origin)
    r.check("D1 Content-Disposition has a file name", "filename" in header_value(download, "Content-Disposition").lower(),
            header_value(download, "Content-Disposition"))
    r.check(f"D1 Access-Control-Expose-Headers includes Content-Disposition for {origin}",
            "content-disposition" in header_value(download, "Access-Control-Expose-Headers").lower(),
            header_value(download, "Access-Control-Expose-Headers") or "header missing")
    r.expect_status("D1 audit extract as Company Admin", ex.submit("audit-extract", "csv",
                                                                   {"occurredFrom": f"{start}T00:00:00+05:30",
                                                                    "occurredTo": f"{end}T23:59:59+05:30"}), 202)


def main():
    parser = standard_args(argparse.ArgumentParser(description=__doc__,
                                                   formatter_class=argparse.RawDescriptionHelpFormatter))
    today = colombo_today()
    parser.add_argument("--from", dest="start", default=str(today.replace(day=1)))
    parser.add_argument("--to", dest="end", default=str(today))
    args = parser.parse_args()
    env = load_env(args.env)
    report = Report("report-export")
    base = audit_base(env, args.target)
    print(f"Target: {args.target} ({base})")
    from sellora_qa import require_api
    require_api(args, report, base, "AUDIT_GW")
    s = build_scenario(args, env, report, delivery_base(env, args.target))
    from sellora_qa import audit_preflight
    audit_preflight(s, report, base)
    from datetime import date
    ex, ctx = Exports(s, base), {"range": (date.fromisoformat(args.start), date.fromisoformat(args.end))}

    report.story(STORY, "US-E7-3 Report export")
    run_case(report, "US-E7-3-Q1", "CSV and PDF match the screen", q1_matches_screen, s, report, ctx, ex)
    run_case(report, "US-E7-3-Q2", "Scope", q2_area_manager, s, report, ctx, ex)
    run_case(report, "US-E7-3-Q3", "Large export", q3_large, s, report, ctx, ex)
    run_case(report, "US-E7-3-Q4", "Access and expiry", q4_access_expiry, s, report, ctx, ex)
    run_case(report, "US-E7-3-D1", "Binary responses through APIM and CORS", d1_headers, s, report, ctx, ex)
    report.finish(args.evidence, args.target, base)


if __name__ == "__main__":
    main()