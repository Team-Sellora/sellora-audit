using System.Globalization;
using System.Text;

namespace Sellora.AuditService.Application.Exports;

/// <summary>A cell that remembers whether it is a number, so writers never treat figures as text.</summary>
public readonly record struct ExportCell(string Text, bool IsNumber)
{
    public static implicit operator ExportCell(string? text) => new(text ?? string.Empty, false);

    public static implicit operator ExportCell(int value) => new(value.ToString(CultureInfo.InvariantCulture), true);

    public static implicit operator ExportCell(long value) => new(value.ToString(CultureInfo.InvariantCulture), true);

    public static implicit operator ExportCell(decimal value) => new(value.ToString("0.00", CultureInfo.InvariantCulture), true);

    public static ExportCell Percent(decimal? value) =>
        value is { } percent ? new(percent.ToString("0.0", CultureInfo.InvariantCulture), true) : new(string.Empty, false);
}

/// <summary>The header block every export starts with.</summary>
public sealed record ExportStamp(string GeneratedBy, DateTimeOffset GeneratedAt, string Filters, string Scope)
{
    public IReadOnlyList<KeyValuePair<string, string>> Lines() => new[]
    {
        new KeyValuePair<string, string>("Generated by", GeneratedBy),
        new KeyValuePair<string, string>("Generated at", GeneratedAt.UtcDateTime.ToString("yyyy-MM-dd HH:mm:ss 'UTC'", CultureInfo.InvariantCulture)),
        new KeyValuePair<string, string>("Filters", Filters),
        new KeyValuePair<string, string>("Scope", Scope)
    };
}

/// <summary>A report as one table; CSV and PDF render the same one, so both hold the same figures.</summary>
public sealed record ExportTable(
    string Title,
    ExportStamp Stamp,
    IReadOnlyList<string> Columns,
    IReadOnlyList<IReadOnlyList<ExportCell>> Rows,
    IReadOnlyList<KeyValuePair<string, string>>? Notes = null)
{
    public IReadOnlyList<KeyValuePair<string, string>> HeaderLines() =>
        Stamp.Lines().Concat(Notes ?? Array.Empty<KeyValuePair<string, string>>()).ToList();
}

/// <summary>US-E7-3-BE2: RFC 4180 CSV, CRLF, UTF-8 with BOM so Excel shows Sinhala and Tamil.</summary>
public static class CsvExportWriter
{
    public const string ContentType = "text/csv; charset=utf-8";

    private static readonly char[] NeedsQuotes = { ',', '"', '\r', '\n' };

    public static byte[] Write(ExportTable table)
    {
        ArgumentNullException.ThrowIfNull(table);

        using var stream = new MemoryStream();

        using (var writer = new StreamWriter(stream, new UTF8Encoding(encoderShouldEmitUTF8Identifier: true)) { NewLine = "\r\n" })
        {
            WriteRow(writer, new ExportCell[] { table.Title });

            foreach (var (key, value) in table.HeaderLines())
            {
                WriteRow(writer, new ExportCell[] { key, value });
            }

            writer.WriteLine();
            WriteRow(writer, table.Columns.Select(column => (ExportCell)column).ToList());

            foreach (var row in table.Rows)
            {
                WriteRow(writer, row);
            }
        }

        return stream.ToArray();
    }

    public static string Field(ExportCell cell)
    {
        if (cell.IsNumber)
        {
            return cell.Text;
        }

        // A text cell starting like a formula would run in a spreadsheet.
        var text = cell.Text.Length > 0 && cell.Text[0] is '=' or '+' or '-' or '@' or '\t' or '\r'
            ? "'" + cell.Text
            : cell.Text;

        return text.IndexOfAny(NeedsQuotes) >= 0
            ? "\"" + text.Replace("\"", "\"\"") + "\""
            : text;
    }

    private static void WriteRow(TextWriter writer, IReadOnlyList<ExportCell> cells)
    {
        for (var index = 0; index < cells.Count; index++)
        {
            if (index > 0)
            {
                writer.Write(',');
            }

            writer.Write(Field(cells[index]));
        }

        writer.WriteLine();
    }
}
