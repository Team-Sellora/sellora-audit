using System.Globalization;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using Sellora.AuditService.Application.Exports;

namespace Sellora.AuditService.Infrastructure.Exports;

/// <summary>US-E7-3-BE2: polished landscape A4 executive PDF report.</summary>
public static class PdfExportWriter
{
    public const string ContentType = "application/pdf";

    private const string BrandTeal = "#0f766e";
    private const string MutedText = "#64748b";
    private const string InkText = "#0f172a";
    private const string DarkSlate = "#1e293b";
    private const string PanelFill = "#f1f5f9";
    private const string StripeFill = "#f8fafc";
    private const string PanelBorder = "#cbd5e1";
    private const string RuleLine = "#e2e8f0";
    private const string FooterText = "#94a3b8";

    /// <summary>Called once at startup.</summary>
    public static void UseCommunityLicence() => QuestPDF.Settings.License = LicenseType.Community;

    private static string FormatCellText(ExportCell cell)
    {
        if (cell.IsNumber && decimal.TryParse(cell.Text, NumberStyles.Any, CultureInfo.InvariantCulture, out var num))
        {
            return cell.Text.Contains('.')
                ? num.ToString("#,##0.00", CultureInfo.InvariantCulture)
                : num.ToString("#,##0", CultureInfo.InvariantCulture);
        }

        return cell.Text;
    }

    public static byte[] Write(ExportTable table)
    {
        ArgumentNullException.ThrowIfNull(table);

        return Document.Create(document => document.Page(page =>
        {
            page.Size(PageSizes.A4.Landscape());
            page.Margin(28);
            page.DefaultTextStyle(style => style.FontSize(8).FontFamily("Arial"));

            page.Header().PaddingBottom(10).Column(column => ComposeHeader(column, table));
            page.Content().Table(grid => ComposeTable(grid, table));
            page.Footer().PaddingTop(8).BorderTop(0.5f).BorderColor(Color.FromHex(PanelBorder)).Row(ComposeFooter);
        })).GeneratePdf();
    }

    private static void ComposeHeader(ColumnDescriptor column, ExportTable table)
    {
        // Brand and title row
        column.Item().Row(row =>
        {
            row.RelativeItem().Column(titleCol => ComposeTitle(titleCol, table.Title));
            row.AutoItem().AlignRight().Column(metaCol => ComposeScope(metaCol, table.Stamp.Scope));
        });

        // Horizontal accent divider
        column.Item().PaddingTop(6).PaddingBottom(8)
            .LineHorizontal(1.5f)
            .LineColor(Color.FromHex(BrandTeal));

        // Metadata cards
        column.Item().Background(Color.FromHex(StripeFill))
            .Border(1)
            .BorderColor(Color.FromHex(RuleLine))
            .Padding(8)
            .Row(metaRow => ComposeMetadata(metaRow, table.Stamp));
    }

    private static void ComposeTitle(ColumnDescriptor titleCol, string title)
    {
        titleCol.Item().Row(brandRow =>
        {
            brandRow.AutoItem()
                .Background(Color.FromHex(BrandTeal))
                .PaddingVertical(2)
                .PaddingHorizontal(6)
                .Text("SELLORA")
                .FontSize(7.5f)
                .Bold()
                .FontColor(Colors.White);

            brandRow.AutoItem()
                .PaddingLeft(6)
                .AlignMiddle()
                .Text("FIELD SALES MANAGEMENT PLATFORM")
                .FontSize(7)
                .SemiBold()
                .FontColor(Color.FromHex(MutedText));
        });

        titleCol.Item().PaddingTop(4)
            .Text(title)
            .FontSize(16)
            .Bold()
            .FontColor(Color.FromHex(InkText));
    }

    private static void ComposeScope(ColumnDescriptor metaCol, string scope)
    {
        metaCol.Item()
            .Background(Color.FromHex(PanelFill))
            .Border(1)
            .BorderColor(Color.FromHex(PanelBorder))
            .PaddingVertical(4)
            .PaddingHorizontal(8)
            .Text(text =>
            {
                text.Span("Scope: ").FontSize(7.5f).SemiBold().FontColor(Color.FromHex(MutedText));
                text.Span(scope).FontSize(7.5f).Bold().FontColor(Color.FromHex(InkText));
            });
    }

    private static void ComposeMetadata(RowDescriptor metaRow, ExportStamp stamp)
    {
        metaRow.RelativeItem().Column(c => ComposeMetadataCard(c, "GENERATED BY", stamp.GeneratedBy));

        metaRow.RelativeItem().Column(c => ComposeMetadataCard(c, "GENERATED AT",
            stamp.GeneratedAt.UtcDateTime.ToString("yyyy-MM-dd HH:mm:ss 'UTC'", CultureInfo.InvariantCulture)));

        metaRow.RelativeItem(2).Column(c => ComposeMetadataCard(c, "FILTERS APPLIED",
            string.IsNullOrWhiteSpace(stamp.Filters) ? "None" : stamp.Filters));
    }

    private static void ComposeMetadataCard(ColumnDescriptor card, string label, string value)
    {
        card.Item().Text(label).FontSize(6.5f).Bold().FontColor(Color.FromHex(MutedText));
        card.Item().Text(value).FontSize(7.5f).FontColor(Color.FromHex(InkText));
    }

    private static void ComposeTable(TableDescriptor grid, ExportTable table)
    {
        grid.ColumnsDefinition(columns =>
        {
            for (var i = 0; i < table.Columns.Count; i++)
            {
                columns.RelativeColumn(i == 0 && table.Columns.Count > 2 ? 1.4f : 1.0f);
            }
        });

        grid.Header(headerRow =>
        {
            for (var i = 0; i < table.Columns.Count; i++)
            {
                ComposeHeaderCell(headerRow, table.Columns[i], IsNumberColumn(table, i));
            }
        });

        for (var rowIndex = 0; rowIndex < table.Rows.Count; rowIndex++)
        {
            ComposeBodyRow(grid, table.Rows[rowIndex], rowIndex);
        }
    }

    private static bool IsNumberColumn(ExportTable table, int columnIndex) =>
        table.Rows.Count > 0 && table.Rows[0].Count > columnIndex && table.Rows[0][columnIndex].IsNumber;

    private static void ComposeHeaderCell(TableCellDescriptor headerRow, string title, bool isNumber)
    {
        var cell = headerRow.Cell()
            .Background(Color.FromHex(DarkSlate))
            .PaddingVertical(6)
            .PaddingHorizontal(8);

        Align(cell, isNumber).Text(title).FontSize(8.5f).Bold().FontColor(Colors.White);
    }

    private static void ComposeBodyRow(TableDescriptor grid, IReadOnlyList<ExportCell> row, int rowIndex)
    {
        var isTotal = row.Count > 0 && row[0].Text.Trim().Equals("Total", StringComparison.OrdinalIgnoreCase);
        var background = RowBackground(isTotal, rowIndex);

        foreach (var cell in row)
        {
            ComposeBodyCell(grid, cell, isTotal, background);
        }
    }

    private static Color RowBackground(bool isTotal, int rowIndex)
    {
        if (isTotal)
        {
            return Color.FromHex(PanelFill);
        }

        return rowIndex % 2 == 0 ? Colors.White : Color.FromHex(StripeFill);
    }

    private static void ComposeBodyCell(TableDescriptor grid, ExportCell cell, bool isTotal, Color background)
    {
        var cellBox = grid.Cell()
            .Background(background)
            .PaddingVertical(isTotal ? 6 : 5)
            .PaddingHorizontal(8);

        cellBox = isTotal
            ? cellBox.BorderTop(1.5f).BorderColor(Color.FromHex(DarkSlate))
                     .BorderBottom(1.5f).BorderColor(Color.FromHex(DarkSlate))
            : cellBox.BorderBottom(0.5f).BorderColor(Color.FromHex(RuleLine));

        var styled = Align(cellBox, cell.IsNumber).Text(FormatCellText(cell)).FontSize(isTotal ? 8.5f : 8);

        if (isTotal)
        {
            styled.Bold().FontColor(Color.FromHex(InkText));
        }
        else
        {
            styled.FontColor(Color.FromHex(DarkSlate));
        }
    }

    private static IContainer Align(IContainer container, bool isNumber) =>
        isNumber ? container.AlignRight() : container.AlignLeft();

    private static void ComposeFooter(RowDescriptor footerRow)
    {
        footerRow.RelativeItem()
            .Text("Sellora Distribution Platform • Confidential & Proprietary Report")
            .FontSize(7)
            .FontColor(Color.FromHex(FooterText));

        footerRow.AutoItem().Text(text =>
        {
            text.Span("Page ").FontSize(7).FontColor(Color.FromHex(MutedText));
            text.CurrentPageNumber().FontSize(7).SemiBold().FontColor(Color.FromHex(InkText));
            text.Span(" of ").FontSize(7).FontColor(Color.FromHex(MutedText));
            text.TotalPages().FontSize(7).SemiBold().FontColor(Color.FromHex(InkText));
        });
    }
}
