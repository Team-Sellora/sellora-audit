using System.Globalization;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using Sellora.AuditService.Application.Exports;

namespace Sellora.AuditService.Infrastructure.Exports;

/// <summary>US-E7-3-BE2: polished landscape A4 executive PDF report.</summary>
public static class PdfExportWriter
{
    public const string ContentType = "application/pdf";

    /// <summary>Called once at startup.</summary>
    public static void UseCommunityLicence() => QuestPDF.Settings.License = LicenseType.Community;

    private static string FormatCellText(ExportCell cell)
    {
        if (cell.IsNumber && decimal.TryParse(cell.Text, NumberStyles.Any, CultureInfo.InvariantCulture, out var num))
        {
            return cell.Text.Contains('.')
                ? num.ToString("#,##0.00", CultureInfo.InvariantCulture)
                : num.ToString("#,##0", CultureInfo.InvariantCulture);
        }

        return cell.Text;
    }

    public static byte[] Write(ExportTable table)
    {
        ArgumentNullException.ThrowIfNull(table);

        return Document.Create(document => document.Page(page =>
        {
            page.Size(PageSizes.A4.Landscape());
            page.Margin(28);
            page.DefaultTextStyle(style => style.FontSize(8).FontFamily("Arial"));

            page.Header().PaddingBottom(10).Column(column =>
            {
                // Brand and title row
                column.Item().Row(row =>
                {
                    row.RelativeItem().Column(titleCol =>
                    {
                        titleCol.Item().Row(brandRow =>
                        {
                            brandRow.AutoItem()
                                .Background(Color.FromHex("#0f766e"))
                                .PaddingVertical(2)
                                .PaddingHorizontal(6)
                                .Text("SELLORA")
                                .FontSize(7.5f)
                                .Bold()
                                .FontColor(Colors.White);

                            brandRow.AutoItem()
                                .PaddingLeft(6)
                                .AlignMiddle()
                                .Text("FIELD SALES MANAGEMENT PLATFORM")
                                .FontSize(7)
                                .SemiBold()
                                .FontColor(Color.FromHex("#64748b"));
                        });

                        titleCol.Item().PaddingTop(4)
                            .Text(table.Title)
                            .FontSize(16)
                            .Bold()
                            .FontColor(Color.FromHex("#0f172a"));
                    });

                    row.AutoItem().AlignRight().Column(metaCol =>
                    {
                        metaCol.Item()
                            .Background(Color.FromHex("#f1f5f9"))
                            .Border(1)
                            .BorderColor(Color.FromHex("#cbd5e1"))
                            .PaddingVertical(4)
                            .PaddingHorizontal(8)
                            .Text(text =>
                            {
                                text.Span("Scope: ").FontSize(7.5f).SemiBold().FontColor(Color.FromHex("#64748b"));
                                text.Span(table.Stamp.Scope).FontSize(7.5f).Bold().FontColor(Color.FromHex("#0f172a"));
                            });
                    });
                });

                // Horizontal accent divider
                column.Item().PaddingTop(6).PaddingBottom(8)
                    .LineHorizontal(1.5f)
                    .LineColor(Color.FromHex("#0f766e"));

                // Metadata cards
                column.Item().Background(Color.FromHex("#f8fafc"))
                    .Border(1)
                    .BorderColor(Color.FromHex("#e2e8f0"))
                    .Padding(8)
                    .Row(metaRow =>
                    {
                        metaRow.RelativeItem().Column(c =>
                        {
                            c.Item().Text("GENERATED BY").FontSize(6.5f).Bold().FontColor(Color.FromHex("#64748b"));
                            c.Item().Text(table.Stamp.GeneratedBy).FontSize(7.5f).FontColor(Color.FromHex("#0f172a"));
                        });

                        metaRow.RelativeItem().Column(c =>
                        {
                            c.Item().Text("GENERATED AT").FontSize(6.5f).Bold().FontColor(Color.FromHex("#64748b"));
                            c.Item().Text(table.Stamp.GeneratedAt.UtcDateTime.ToString("yyyy-MM-dd HH:mm:ss 'UTC'", CultureInfo.InvariantCulture))
                                .FontSize(7.5f).FontColor(Color.FromHex("#0f172a"));
                        });

                        metaRow.RelativeItem(2).Column(c =>
                        {
                            c.Item().Text("FILTERS APPLIED").FontSize(6.5f).Bold().FontColor(Color.FromHex("#64748b"));
                            c.Item().Text(string.IsNullOrWhiteSpace(table.Stamp.Filters) ? "None" : table.Stamp.Filters)
                                .FontSize(7.5f).FontColor(Color.FromHex("#0f172a"));
                        });
                    });
            });

            page.Content().Table(grid =>
            {
                grid.ColumnsDefinition(columns =>
                {
                    for (var i = 0; i < table.Columns.Count; i++)
                    {
                        if (i == 0 && table.Columns.Count > 2)
                        {
                            columns.RelativeColumn(1.4f);
                        }
                        else
                        {
                            columns.RelativeColumn(1.0f);
                        }
                    }
                });

                grid.Header(headerRow =>
                {
                    for (var i = 0; i < table.Columns.Count; i++)
                    {
                        var col = table.Columns[i];
                        var isNum = table.Rows.Count > 0 && table.Rows[0].Count > i && table.Rows[0][i].IsNumber;
                        var cell = headerRow.Cell()
                            .Background(Color.FromHex("#1e293b"))
                            .PaddingVertical(6)
                            .PaddingHorizontal(8);

                        if (isNum)
                        {
                            cell.AlignRight().Text(col).FontSize(8.5f).Bold().FontColor(Colors.White);
                        }
                        else
                        {
                            cell.AlignLeft().Text(col).FontSize(8.5f).Bold().FontColor(Colors.White);
                        }
                    }
                });

                for (var rowIndex = 0; rowIndex < table.Rows.Count; rowIndex++)
                {
                    var row = table.Rows[rowIndex];
                    var isTotal = row.Count > 0 && row[0].Text.Trim().Equals("Total", StringComparison.OrdinalIgnoreCase);
                    var bg = isTotal
                        ? Color.FromHex("#f1f5f9")
                        : (rowIndex % 2 == 0 ? Colors.White : Color.FromHex("#f8fafc"));

                    for (var colIndex = 0; colIndex < row.Count; colIndex++)
                    {
                        var cell = row[colIndex];
                        var cellBox = grid.Cell()
                            .Background(bg)
                            .PaddingVertical(isTotal ? 6 : 5)
                            .PaddingHorizontal(8);

                        if (isTotal)
                        {
                            cellBox = cellBox.BorderTop(1.5f).BorderColor(Color.FromHex("#1e293b"))
                                             .BorderBottom(1.5f).BorderColor(Color.FromHex("#1e293b"));
                        }
                        else
                        {
                            cellBox = cellBox.BorderBottom(0.5f).BorderColor(Color.FromHex("#e2e8f0"));
                        }

                        var text = FormatCellText(cell);
                        if (cell.IsNumber)
                        {
                            var styled = cellBox.AlignRight().Text(text).FontSize(isTotal ? 8.5f : 8);
                            if (isTotal) styled.Bold().FontColor(Color.FromHex("#0f172a"));
                            else styled.FontColor(Color.FromHex("#1e293b"));
                        }
                        else
                        {
                            var styled = cellBox.AlignLeft().Text(text).FontSize(isTotal ? 8.5f : 8);
                            if (isTotal) styled.Bold().FontColor(Color.FromHex("#0f172a"));
                            else styled.FontColor(Color.FromHex("#1e293b"));
                        }
                    }
                }
            });

            page.Footer().PaddingTop(8).BorderTop(0.5f).BorderColor(Color.FromHex("#cbd5e1")).Row(footerRow =>
            {
                footerRow.RelativeItem()
                    .Text("Sellora Distribution Platform • Confidential & Proprietary Report")
                    .FontSize(7)
                    .FontColor(Color.FromHex("#94a3b8"));

                footerRow.AutoItem().Text(text =>
                {
                    text.Span("Page ").FontSize(7).FontColor(Color.FromHex("#64748b"));
                    text.CurrentPageNumber().FontSize(7).SemiBold().FontColor(Color.FromHex("#0f172a"));
                    text.Span(" of ").FontSize(7).FontColor(Color.FromHex("#64748b"));
                    text.TotalPages().FontSize(7).SemiBold().FontColor(Color.FromHex("#0f172a"));
                });
            });
        })).GeneratePdf();
    }
}
